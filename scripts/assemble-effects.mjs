#!/usr/bin/env node
/**
 * Assemble the physics effects into the client bundle.
 *
 * The effects are written as standalone snippets (lib/effects/<id>.js) so they
 * can be built and checked in parallel with `scripts/effect-harness.mjs`. There
 * is no build step at runtime, so this script splices the snippets into
 * lib/client.js between two markers, in a fixed order.
 *
 *   node scripts/assemble-effects.mjs [--check]
 *
 * --check verifies that the bundle already contains exactly what the snippets
 * would produce (used by tests / CI) and exits non-zero when it drifted.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const clientPath = join(here, 'lib', 'client.js')

/**
 * Read a source file with LF endings. A Windows checkout with CRLF must not
 * make `--check` fail: the assembled block is always joined with LF, so both
 * sides are normalized before comparing.
 */
function readNormalized(path) {
  return readFileSync(path, 'utf8').replace(/\r\n?/gu, '\n')
}

/** Declaration order in the menu, and the variable each file must export. */
const EFFECTS = [
  { file: 'double-pendulum.js', name: 'doublePendulumEffect' },
  { file: 'spring-mesh.js', name: 'springMeshEffect' },
  { file: 'gyroscope.js', name: 'gyroscopeEffect' },
  { file: 'dominoes.js', name: 'dominoesEffect' },
  // ---- 几何线条 ----
  { file: 'spirograph.js', name: 'spirographEffect' },
  { file: 'fourier-epicycles.js', name: 'fourierEpicyclesEffect' },
  // ---- 粒子场 / 群集 ----
  { file: 'flow-field.js', name: 'flowFieldEffect' },
  { file: 'boids.js', name: 'boidsEffect' },
  { file: 'accretion-disk.js', name: 'accretionDiskEffect' },
  { file: 'sandstorm.js', name: 'sandstormEffect' },
  { file: 'fireflies.js', name: 'firefliesEffect' },
  // ---- 伪 3D / 视差 ----
  // ---- 能量核心 ----
  { file: 'concentric-core.js', name: 'concentricCoreEffect' },
  // ---- 交互反馈 ----
  { file: 'ripple.js', name: 'rippleEffect' },
  { file: 'burst.js', name: 'burstEffect' },
  { file: 'ticks.js', name: 'ticksEffect' },
  // ---- 材质与氛围 ----
  { file: 'film-grain.js', name: 'filmGrainEffect' },
  { file: 'nebula.js', name: 'nebulaEffect' },
  { file: 'flames.js', name: 'flamesEffect' },
  // ---- 数据与文字 ----
  { file: 'seven-segment.js', name: 'sevenSegmentEffect' },
  { file: 'segments.js', name: 'segmentsEffect' },
  { file: 'gauge.js', name: 'gaugeEffect' },
  // ---- 生命 / 角色 ----
  { file: 'jellyfish.js', name: 'jellyfishEffect' },
  { file: 'vine.js', name: 'vineEffect' },
  { file: 'microbe.js', name: 'microbeEffect' },
  { file: 'bloom.js', name: 'bloomEffect' },
  // ---- 形变与过渡 ----
  { file: 'metaballs.js', name: 'metaballsEffect' },
  { file: 'squash.js', name: 'squashEffect' },
  { file: 'polar.js', name: 'polarEffect' },
  // ---- 光与色 ----
  { file: 'aurora.js', name: 'auroraEffect' },
  { file: 'afterglow.js', name: 'afterglowEffect' },
  { file: 'embers.js', name: 'embersEffect' },
  // ---- 波形信号 ----
  { file: 'harmonics.js', name: 'harmonicsEffect' },
  { file: 'chirp.js', name: 'chirpEffect' },
  { file: 'standing-wave.js', name: 'standingWaveEffect' },
]

const START = '\t\t// ---- physics effects: generated by scripts/assemble-effects.mjs ----'
const END = '\t\t// ---- end physics effects ----'

function assemble() {
  const parts = []
  for (const entry of EFFECTS) {
    const path = join(here, 'lib', 'effects', entry.file)
    if (!existsSync(path)) throw new Error(`missing snippet: lib/effects/${entry.file}`)
    const source = readNormalized(path).trimEnd()
    if (!source.includes(`const ${entry.name} = {`)) {
      throw new Error(`lib/effects/${entry.file} must declare const ${entry.name} = { ... }`)
    }
    parts.push(source)
  }
  const names = EFFECTS.map((entry) => entry.name)
  return [
    START,
    ...parts.flatMap((part) => ['', part]),
    '',
    `\t\tconst PHYSICS_EFFECTS = [${names.join(', ')}]`,
    '',
    END,
  ].join('\n')
}

const client = readNormalized(clientPath)
const start = client.indexOf(START)
const end = client.indexOf(END)
if (start < 0 || end < 0) throw new Error('markers not found in lib/client.js')

const block = assemble()
const next = client.slice(0, start) + block + client.slice(end + END.length)

if (process.argv.includes('--check')) {
  if (next !== client) {
    console.error('lib/client.js is out of date — run: node scripts/assemble-effects.mjs')
    process.exit(1)
  }
  console.log('physics effects are in sync')
  process.exit(0)
}

writeFileSync(clientPath, next)
console.log(`assembled ${EFFECTS.length} effects into lib/client.js`)
